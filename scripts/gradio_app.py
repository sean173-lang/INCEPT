def display(bundle,provenance,notice=None):
    bundle=validate_bundle(bundle.model_dump(mode='json'))
    docs={d.kind:d for d in bundle.documents}
    mode=provenance['mode']
    banner=('**REAL LOCAL n8n EXECUTION #'+provenance['execution_id']+' — deterministic DEMO backend result.**' if mode=='real_local_n8n' else '**SAVED SYNTHETIC DEMO FIXTURE — not a new n8n or AI execution.**')
    if notice:banner='**n8n run unavailable:** '+text(notice)+'\n\n'+banner
    banner+='\n\nFictional client and dispute. No paid AI, registry calls, outgoing messages, mandate acceptance or invoice issuance.'
    validation=['## Document checks','', '| Draft | Template | Status | Issued / approved |','|---|---|---|---|']
    for d in bundle.documents:
        validation.append('| '+text(d.kind)+' | '+d.template_version+' | '+d.completeness_status+' | No / No |')
    validation+=['','**Five-hour demo advance: €1,250.00 net + €237.50 VAT = €1,487.50.**','Explicit synthetic 19% VAT assumption; not tax advice or an issued invoice.']
    for d in bundle.documents:
        validation+=['','### '+text(d.kind),'']+['- '+text(v) for v in d.missing_information]
        validation+=['- '+text(i.description) for i in d.validation_issues]
    validation+=['','## Missing case information','']+['- '+text(v) for v in bundle.assessment.missing_information]
    validation+=['','## Review warnings','']+['- '+text(w.message) for w in bundle.assessment.review_warnings]
    actions=['## Five actions — all pending lawyer approval','','No approve, send, schedule or issue control exists in this demo.']
    for index,a in enumerate(bundle.proposed_actions,1):
        actions+=['','### '+str(index)+'. '+text(a.title),'**'+a.state+'** · executed: No · confirmed due date: None','',text(a.detail)]
        if a.kind=='draft_email':actions+=['','**Unsent email draft** — '+text(a.subject or ''),'',text(a.body or '')]
        if a.kind=='potential_deadline':actions+=['','Potential deadline only. Missing trigger evidence prevents a confirmed calculation.']
    return (banner,bundle.assessment.content_markdown,docs['vollmacht'].content_markdown,
            docs['fee_agreement'].content_markdown,docs['advance_invoice'].content_markdown,
            '\n'.join(validation),'\n'.join(actions),provenance)


class DemoUI:
    def __init__(self,runner=None):self.runner=runner or DemoRunner()
    def saved(self,notice=None):
        try:return display(load_saved(),{'mode':'saved_demo_fixture','execution_id':None,'business_success':False,'origin':'synthetic bundle generated by real onboarding code offline','provider_requests':0,'external_actions':0,'ai_mode':'disabled; deterministic assessment'},notice)
        except Exception:return ('Demo fixture unavailable or invalid. No result is claimed.',*(['Unavailable']*6),{'mode':'unavailable','execution_id':None})
    def run(self):
        try:
            bundle,proof=self.runner.run();return display(bundle,proof)
        except DemoError as error:return self.saved(str(error))
        except Exception:return self.saved('Unexpected local demo error. No successful execution is claimed; inspect the private runtime log.')


